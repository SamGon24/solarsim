int cmdRender(AppContext& ctx) {
    const std::string out = ctx.args().getString("out", "solarsim.gif");
    const std::string lower = str::toLower(out);
    const bool isGif = str::endsWith(lower, ".gif");
    const bool isSvg = str::endsWith(lower, ".svg");
    const bool isDir = str::endsWith(out, "/") || str::endsWith(out, "\\");
    const bool isStillFormat = !isGif && !isSvg && !isDir;

    const int W = static_cast<int>(ctx.args().getInt("width", 960));
    const int H = static_cast<int>(ctx.args().getInt("height", 540));
    if (W < 32 || H < 32 || W > 8192 || H > 8192) throw UsageError("image size must be within 32..8192 pixels");
    int frames = static_cast<int>(ctx.args().getInt("frames", isStillFormat ? 1 : 240));
    if (frames < 1 || frames > 100000) throw UsageError("--frames must be within 1..100000");
    double dpf = ctx.args().getDouble("days-per-frame", 3.0);
    if (ctx.args().has("duration")) dpf = ctx.args().getDouble("duration", 0.0) / std::max(1, frames - 1);
    const int fps = static_cast<int>(ctx.args().getInt("fps", 30));
    if (fps < 1 || fps > 100) throw UsageError("--fps must be within 1..100");
    const double orbitDeg = ctx.args().getDouble("orbit-camera", 0.0);
    const bool hud = !ctx.args().flag("no-hud");

    auto sim = ctx.makeSimulation(ctx.epoch());
    render::SceneRenderer renderer;
    ctx.configureRenderer(renderer, H);
    if (isSvg) {
        const double total = ctx.args().has("duration") ? ctx.args().getDouble("duration", 365.25) : std::max(365.25, dpf * frames);
        return renderSvg(ctx, *sim, renderer, out, total);
    }

    const double warmup = ctx.args().getDouble("warmup", 0.0);
    if (warmup > 0.0) {
        const int chunks = std::max(1, static_cast<int>(warmup / 2.0));
        for (int k = 0; k < chunks; ++k) {
            sim->advance(warmup / chunks);
            renderer.record(*sim);
            if (!ctx.quiet() && k % 50 == 0) printProgress("warm-up  ", double(k) / chunks);
        }
        if (!ctx.quiet()) finishProgress();
    }
    renderer.record(*sim);

    render::Camera cam;
    ctx.configureCamera(cam, renderer, sim->system(), W, H);
    const int focus = ctx.focusIndex(sim->system());
    renderer.options().focus = -1;
    const render::PostSettings post = ctx.postSettings();

    render::Framebuffer fb(W, H);
    render::Image8 img;
    io::GifEncoder gif;
    if (isGif && !gif.open(out, W, H, 0)) throw std::runtime_error("GIF: " + gif.error());
    if (isDir && !platform::makeDirectories(out)) throw std::runtime_error("cannot create directory " + out);

    std::string stem = out, ext = ".png";
    if (isStillFormat) {
        const auto dot = out.find_last_of('.');
        const auto slash = out.find_last_of("/\\");
        if (dot != std::string::npos && (slash == std::string::npos || dot > slash)) {
            stem = out.substr(0, dot);
            ext = out.substr(dot);
        }
    }

    Stopwatch sw;
    double renderTime = 0.0;
    for (int f = 0; f < frames; ++f) {
        if (f > 0) advanceWithTrails(*sim, renderer, dpf);
        if (focus >= 0) cam.setTarget(renderer.displayPosition(sim->system(), static_cast<std::size_t>(focus)));
        if (orbitDeg != 0.0 && f > 0) cam.orbit(orbitDeg * DEG2RAD, 0.0);
        Stopwatch rs;
        renderer.render(*sim, cam, fb);
        render::finishFrame(fb, img, post);
        renderer.drawOverlay(img, hud ? hudLines(*sim, renderer) : std::vector<std::string>{});
        renderTime += rs.seconds();

        std::string err;
        if (isGif) {
            if (!gif.addFrame(img, static_cast<int>(std::lround(100.0 / fps)), ctx.args().flag("dither")))
                throw std::runtime_error("GIF: " + gif.error());
        } else if (isDir) {
            const std::string path = out + str::format("frame_%05d.png", f);
            if (!io::writeImage(path, img, err)) throw std::runtime_error(err);
        } else {
            const std::string path = frames == 1 ? out : stem + str::format("_%04d", f) + ext;
            if (!io::writeImage(path, img, err)) throw std::runtime_error(err);
        }
        if (!ctx.quiet()) printProgress(str::format("frame %d/%d", f + 1, frames), double(f + 1) / frames);
        if (platform::interruptRequested()) {
            log::warn("interrupted - finishing the file with the frames rendered so far");
            break;
        }
    }
    if (!ctx.quiet()) finishProgress();
    if (isGif) {
        gif.close();
        std::printf("wrote %s (%d frames, %dx%d, %s) ", out.c_str(), gif.frameCount(), W, H,
                    str::formatBytes(double(gif.bytesWritten())).c_str());
    } else if (isDir) {
        std::printf("wrote %d frames to %s ", frames, out.c_str());
    } else {
        std::printf("wrote %s ", frames == 1 ? out.c_str() : (stem + "_####" + ext).c_str());
    }
    std::printf("in %s (rendering %s), simulated %s .. %s\n", str::formatDuration(sw.seconds()).c_str(),
                str::formatDuration(renderTime).c_str(), astro::formatDateOnly(sim->epoch()).c_str(),
                astro::formatDateOnly(sim->time()).c_str());
    return 0;
}

