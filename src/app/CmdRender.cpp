std::string hexColor(std::uint32_t c) { return str::format("#%06X", c & 0xFFFFFF); }

std::vector<std::string> hudLines(const physics::Simulation& sim, const render::SceneRenderer& r) {
    const auto e = sim.invariantErrors();
    return {"SolarSim  " + astro::formatUTC(sim.time(), false),
            str::format("%s  dt %.3f d  dE/E %+.1e%s  scale %s", sim.integrator().name().c_str(), sim.timeStep(),
                        e.energyRel, sim.relativity() ? "  GR" : "", render::scaleModeName(r.mapping().mode()))};
}

// Advances the simulation by `days`, recording trail samples along the way.
void advanceWithTrails(physics::Simulation& sim, render::SceneRenderer& r, double days) {
    // Sub-steps of at least four integrator steps keep trail sampling smooth
    // without fragmenting the integration.
    const double chunk = std::max(0.25, 4.0 * sim.timeStep());
    const int sub = std::clamp(static_cast<int>(std::ceil(std::fabs(days) / chunk)), 1, 64);
    for (int k = 0; k < sub; ++k) {
        sim.advance(days / sub);
        r.record(sim);
    }
}

int renderSvg(AppContext& ctx, physics::Simulation& sim, render::SceneRenderer& r, const std::string& path,
              double totalDays) {
    const int W = static_cast<int>(ctx.args().getInt("width", 1000));
    const int H = static_cast<int>(ctx.args().getInt("height", 1000));
    auto& sys = sim.system();
    r.mapping().prepare(sys);
    // Extent in display units.
    double extent = 1.0;
    for (std::size_t i = 1; i < sys.namedCount(); ++i)
        if (sys.info(i).parent == 0) extent = std::max(extent, r.mapping().radial((sys.pos(i) - sys.pos(0)).norm()));
    const double scale = 0.46 * std::min(W, H) / (extent * 1.05);
    const double cx = W / 2.0, cy = H / 2.0;
    auto P = [&](const Vec3& d) { return std::make_pair(cx + d.x * scale, cy - d.y * scale); };

    io::SvgWriter svg(W, H);
    svg.comment("Generated by SolarSim - view from the north ecliptic pole, radial scale: " +
                std::string(render::scaleModeName(r.mapping().mode())));
    const double start = sim.time();
    // Distance rings.
    for (double au : {1.0, 2.0, 5.0, 10.0, 20.0, 30.0, 40.0, 50.0}) {
        const double rr = r.mapping().radial(au);
        if (rr > extent * 1.05) break;
        svg.circle(cx, cy, rr * scale, "none", "#1d2840", 1.0);
        svg.text(cx + 4, cy - rr * scale - 3, str::format("%g AU", au), "#45577a", 11);
    }
    // Osculating orbits at the start.
    for (std::size_t i = 1; i < sys.namedCount(); ++i) {
        const auto& inf = sys.info(i);
        if (inf.parent != 0) continue;
        const auto el = astro::stateToElements(sys.pos(i) - sys.pos(0), sys.vel(i) - sys.vel(0), sys.twoBodyMu(i), start);
        if (!el.isElliptic()) continue;
        Vec3 Pv, Qv, Wv;
        astro::perifocalBasis(el.i, el.node, el.argp, Pv, Qv, Wv);
        std::vector<std::pair<double, double>> pts;
        const double a = el.a(), b = a * std::sqrt(1 - el.e * el.e);
        for (int k = 0; k < 360; ++k) {
            const double E = TWO_PI * k / 360.0;
            pts.push_back(P(r.mapping().mapHelio(Pv * (a * (std::cos(E) - el.e)) + Qv * (b * std::sin(E)))));
        }
        svg.polyline(pts, hexColor(inf.color), 1.0, 0.35, true, "4 3");
    }
    // Integrate and trace paths.
    std::vector<std::vector<std::pair<double, double>>> paths(sys.namedCount());
    const int samples = 600;
    for (int k = 0; k <= samples; ++k) {
        if (k > 0) sim.advance(totalDays / samples);
        for (std::size_t i = 1; i < sys.namedCount(); ++i)
            if (sys.info(i).parent == 0) paths[i].push_back(P(r.mapping().position(sys, i)));
        if (!ctx.quiet() && k % 20 == 0) printProgress("tracing", double(k) / samples);
    }
    if (!ctx.quiet()) finishProgress();
    for (std::size_t i = 1; i < sys.namedCount(); ++i) {
        if (paths[i].size() < 2) continue;
        svg.polyline(paths[i], hexColor(sys.info(i).color), 2.0, 0.95, false);
        const auto& end = paths[i].back();
        svg.circle(end.first, end.second, 5.0, hexColor(sys.info(i).color));
        svg.text(end.first + 8, end.second - 6, sys.info(i).name, "#dfe7f2", 13);
    }
    svg.circle(cx, cy, 10, "#ffd43b");
    svg.text(cx + 12, cy + 16, "Sun", "#ffd43b", 13);
    svg.text(20, 30, "SolarSim - " + astro::formatDateOnly(start) + " to " + astro::formatDateOnly(sim.time()), "#e8eef6", 18, "start", "bold");
    svg.text(20, 52, str::format("solid: N-body paths (%.0f days), dashed: osculating orbits at start; radial scale %s",
                                 totalDays, render::scaleModeName(r.mapping().mode())),
             "#8fa0bc", 12);
    std::string err;
    if (!svg.save(path, err)) throw std::runtime_error(err);
    std::printf("wrote %s\n", path.c_str());
    return 0;
}

